def clash_sentence(lang: str, a: str, b: str, risk_text: str, severity: str) -> str:
    template = CLASH[lang]["critical" if severity == "critical" else "major"]
    return template.format(a=a, b=b, risk=risk_text)


def time_of_day(hhmm: str) -> str:
    hour = int(hhmm.split(":")[0])
    if 5 <= hour < 12:
        return "morning"
    if 12 <= hour < 16:
        return "afternoon"
    if 16 <= hour < 20:
        return "evening"
    return "night"


def _join(items: list[str], word: str) -> str:
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + word + items[-1]


def _price(value: Any) -> str:
    number = float(value)
    return str(int(number)) if number == int(number) else f"{number:.2f}"


def _label(med: dict[str, Any]) -> str:
    """Medicine name plus strength, without repeating a strength that is already part of the name."""
    name, dosage = med["name"], med.get("dosage")
    if not dosage:
        return name
    number = re.match(r"\s*([\d.]+)", dosage)
    if number and re.search(rf"(?<![\d.]){re.escape(number.group(1))}(?![\d.])", name):
        return name
    return f"{name} {dosage}"


def _when(p: dict, tod: str, meal_timing: str | None) -> str:
    if meal_timing == "empty_stomach":
        return f"{p['tod'][tod]} {p['meal']['empty_stomach']}"
    if meal_timing:
        meal = p["meal"][meal_timing].format(m=p["meal_noun"][tod])
        return f"{p['tod'][tod]} {meal}" if tod == "morning" else meal
    return p["tod"][tod]


def medicine_sentences(lang: str, med: dict[str, Any], index: int) -> list[str]:
    p = T[lang]
    ordinals = p["ordinals"]
    ordinal = ordinals[index] if index < len(ordinals) else p["ordinal_fallback"].format(i=index + 1)
    label = _label(med)
    out = [p["med_line"].format(ord=ordinal, label=label)]

    times = sorted(med.get("times") or [])
    meal_timing = med.get("meal_timing")
    tods: list[str] = []
    for t in times:
        tod = time_of_day(t)
        if tod not in tods:
            tods.append(tod)

    if len(times) <= 1:
        tod = tods[0] if tods else "morning"
        out.append(p["once"].format(when=_when(p, tod, meal_timing)))
    else:
        text = p["multi"].format(n=len(times), tods=_join([p["tod"][t] for t in tods], p["and"]))
        if meal_timing:
            text += p["each_time"].format(meal=p["meal_generic"][meal_timing])
        out.append(text)

    for code in med.get("avoid_with") or []:
        if code in p["avoid"]:
            out.append(p["avoid"][code])

    brand, generic = med.get("brand_price_inr"), med.get("jan_aushadhi_price_inr")
    if brand is not None and generic is not None and float(generic) < float(brand):
        out.append(p["savings"].format(b=_price(brand), g=_price(generic)))
    return out


def build_summary(lang: str, meds: list[dict[str, Any]], clashes: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    """Return the whole voice note as text plus the individual sentences (for highlighting while playing)."""
    p = T[lang]
    meds = sorted(meds, key=lambda m: (sorted(m.get("times") or ["99:99"])[0], m["name"]))
    n = len(meds)
    sentences = [p["intro_one"] if n == 1 else p["intro_many"].format(n=n)]

    clash_lines = [c["speech"][lang] for c in (clashes or []) if c["severity"] in ("major", "critical")][:3]
    sentences.extend(clash_lines)

    total_savings = 0.0
    for i, med in enumerate(meds):
        sentences.extend(medicine_sentences(lang, med, i))
        b, g = med.get("brand_price_inr"), med.get("jan_aushadhi_price_inr")
        if b is not None and g is not None and float(g) < float(b):
            total_savings += float(b) - float(g)
    sentences.append(p["closing"])

    return {
        "lang": lang,
        "tts_lang_code": TTS_CODES[lang],
        "medicine_count": n,
        "has_clash_warning": bool(clash_lines),
        "total_savings_inr": round(total_savings, 2),
        "sentences": sentences,
        "text": " ".join(sentences),
    }
